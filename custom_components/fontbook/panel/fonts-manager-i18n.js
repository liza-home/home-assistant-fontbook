/** The languages the panel speaks, English first as the source. */
export const LANGUAGES = ["en", "de", "fr", "it", "es"];

/** The two-letter language the user's Home Assistant is set to. */
export function uiLanguage(hass) {
  const tag = hass?.locale?.language || hass?.language || "en";
  const short = String(tag).toLowerCase().split("-")[0];
  return STRINGS[short] ? short : "en";
}

/**
 * One string, with `{placeholders}` filled in.
 *
 * An unknown key answers with the key itself, which is how a backend error
 * code without a translation is told apart from one with.
 */
export function translate(language, key, values = {}) {
  const table = STRINGS[language] || STRINGS.en;
  const text = table[key] ?? STRINGS.en[key];
  if (text === undefined) return key;
  return text.replace(/\{(\w+)\}/g, (whole, name) =>
    values[name] === undefined ? whole : String(values[name]));
}
